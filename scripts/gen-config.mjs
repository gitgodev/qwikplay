// Generates config.js from environment variables (ADMIN_PASSWORD, PLAYS_OFFSET).
// Used locally (npm run gen-config) and mirrors the deploy-pages workflow.
// When an env var is unset, the existing value in config.js is preserved.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

let existingHash = '';
let existingOffset = 0;
try {
  const existing = readFileSync(new URL('../config.js', import.meta.url), 'utf8');
  const hm = existing.match(/window\.QWIK_ADMIN_HASH\s*=\s*"([^"]*)"/);
  if (hm) existingHash = hm[1];
  const om = existing.match(/window\.QWIK_PLAYS_OFFSET\s*=\s*(\d+)/);
  if (om) existingOffset = Number(om[1]) || 0;
} catch {}

const pw = process.env.ADMIN_PASSWORD || '';
const hash = pw ? createHash('sha256').update(pw).digest('hex') : existingHash;

let offset = existingOffset;
if (process.env.PLAYS_OFFSET !== undefined && process.env.PLAYS_OFFSET !== '') {
  offset = Number(process.env.PLAYS_OFFSET) || 0;
}

writeFileSync(new URL('../config.js', import.meta.url),
  `// Generated by scripts/gen-config.mjs (or deploy-pages workflow).\nwindow.QWIK_ADMIN_HASH = "${hash}";\nwindow.QWIK_PLAYS_OFFSET = ${offset};\n`);
console.log(hash ? 'config.js written with admin hash' : 'config.js written (admin open)');
console.log(`plays offset: ${offset}`);