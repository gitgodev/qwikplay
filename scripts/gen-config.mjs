// Generates config.js from the ADMIN_PASSWORD environment variable.
// Used locally (npm run gen-config) and mirrors the deploy-pages workflow.
import { writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const pw = process.env.ADMIN_PASSWORD || '';
const hash = pw ? createHash('sha256').update(pw).digest('hex') : '';
writeFileSync(new URL('../config.js', import.meta.url),
  `// Generated by scripts/gen-config.mjs (or deploy-pages workflow).\nwindow.QWIK_ADMIN_HASH = "${hash}";\n`);
console.log(hash ? 'config.js written with admin hash' : 'config.js written (admin open)');